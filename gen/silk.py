"""Silkscreen: tidy reference designators, label every connector pin / button / LED, back-side title,
pinout + value table for hand assembly, and an original doodle (IR robot). Usage: python3 silk.py board.kicad_pcb"""
import sys, os, math, collections
import pcbnew
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
from circuit import comps

PCB = sys.argv[1]
b = pcbnew.LoadBoard(PCB)
mm = pcbnew.FromMM; ToMM = pcbnew.ToMM
V = lambda x, y: pcbnew.VECTOR2I(mm(float(x)), mm(float(y)))
F, B = pcbnew.F_SilkS, pcbnew.B_SilkS
CENTER, LEFT, RIGHT = pcbnew.GR_TEXT_H_ALIGN_CENTER, pcbnew.GR_TEXT_H_ALIGN_LEFT, pcbnew.GR_TEXT_H_ALIGN_RIGHT

# remove silk generated by a previous run (tagged by a tiny marker in the text)
for d in list(b.GetDrawings()):
    if d.GetLayer() in (F, B) and getattr(d, 'GetText', None) is not None or (d.GetLayer() == B):
        b.Remove(d)

def text(s, x, y, size=1.0, layer=F, just=CENTER, angle=0, bold=False):
    t = pcbnew.PCB_TEXT(b)
    t.SetText(s); t.SetPosition(V(x, y)); t.SetLayer(layer)
    t.SetTextSize(V(size, size)); t.SetTextThickness(mm(max(0.15, size * (0.2 if bold else 0.16))))
    t.SetHorizJustify(just); t.SetMirrored(layer == B)
    t.SetTextAngle(pcbnew.EDA_ANGLE(angle, pcbnew.DEGREES_T))
    b.Add(t); return t

def line(p, q, layer=B, w=0.2):
    s = pcbnew.PCB_SHAPE(b); s.SetShape(pcbnew.SHAPE_T_SEGMENT); s.SetStart(V(*p)); s.SetEnd(V(*q))
    s.SetLayer(layer); s.SetWidth(mm(w)); b.Add(s)

def circle(c, r, layer=B, w=0.2, fill=False):
    s = pcbnew.PCB_SHAPE(b); s.SetShape(pcbnew.SHAPE_T_CIRCLE); s.SetCenter(V(*c)); s.SetEnd(V(c[0] + r, c[1]))
    s.SetLayer(layer); s.SetWidth(mm(w)); s.SetFilled(fill); b.Add(s)

def arc(c, r, a0, a1, layer=B, w=0.2):
    s = pcbnew.PCB_SHAPE(b); s.SetShape(pcbnew.SHAPE_T_ARC); s.SetCenter(V(*c))
    s.SetStart(V(c[0] + r * math.cos(math.radians(a0)), c[1] + r * math.sin(math.radians(a0))))
    s.SetArcAngleAndEnd(pcbnew.EDA_ANGLE(a1 - a0, pcbnew.DEGREES_T)); s.SetLayer(layer); s.SetWidth(mm(w)); b.Add(s)

def rrect(x0, y0, x1, y1, r, layer=B, w=0.2):
    line((x0 + r, y0), (x1 - r, y0), layer, w); line((x1, y0 + r), (x1, y1 - r), layer, w)
    line((x1 - r, y1), (x0 + r, y1), layer, w); line((x0, y1 - r), (x0, y0 + r), layer, w)
    arc((x1 - r, y0 + r), r, 270, 360, layer, w); arc((x1 - r, y1 - r), r, 0, 90, layer, w)
    arc((x0 + r, y1 - r), r, 90, 180, layer, w); arc((x0 + r, y0 + r), r, 180, 270, layer, w)

# ------------------------------------------------------------------ obstacles for top silk
pad_boxes = []
for fp in b.GetFootprints():
    for p in fp.Pads():
        if p.IsOnLayer(pcbnew.F_Cu) or p.GetAttribute() in (pcbnew.PAD_ATTRIB_PTH, pcbnew.PAD_ATTRIB_NPTH):
            bb = p.GetBoundingBox()
            pad_boxes.append((ToMM(bb.GetLeft()) - 0.2, ToMM(bb.GetTop()) - 0.2, ToMM(bb.GetRight()) + 0.2, ToMM(bb.GetBottom()) + 0.2))
placed_boxes = []
court = {}
for fp in b.GetFootprints():
    fp.BuildCourtyardCaches(); cyy = fp.GetCourtyard(pcbnew.F_CrtYd)
    if cyy.OutlineCount() and not fp.GetReference().startswith('U1'):
        bb = cyy.BBox(); court[fp.GetReference()] = (ToMM(bb.GetLeft()), ToMM(bb.GetTop()), ToMM(bb.GetRight()), ToMM(bb.GetBottom()))
CUR = [None]
def overlaps(a, c):
    return not (a[2] < c[0] or c[2] < a[0] or a[3] < c[1] or c[3] < a[1])
def box_of(t):
    bb = t.GetBoundingBox()
    return (ToMM(bb.GetLeft()), ToMM(bb.GetTop()), ToMM(bb.GetRight()), ToMM(bb.GetBottom()))
def score(bx):
    if bx[0] < 100.4 or bx[1] < 100.4 or bx[2] > 175.6 or bx[3] > 155.6:
        return 1000
    s = sum(10 for p in pad_boxes if overlaps(bx, p)) + sum(25 for q in placed_boxes if overlaps(bx, q))
    s += sum(3 for r_, c in court.items() if r_ != CUR[0] and overlaps(bx, c))
    if 126.0 < bx[2] and bx[0] < 150 and bx[1] < 101.8:   # antenna strip
        s += 50
    return s

def place_text(t, cands):
    best = None
    for (x, y) in cands:
        t.SetPosition(V(x, y)); bx = box_of(t); sc = score(bx)
        if best is None or sc < best[0]:
            best = (sc, x, y)
        if sc == 0:
            break
    t.SetPosition(V(best[1], best[2])); placed_boxes.append(box_of(t))
    return best[0]

# ------------------------------------------------------------------ functional labels (placed first)
def label(s, x, y, size=0.9, just=CENTER, angle=0, bold=False):
    t = text(s, x, y, size, F, just, angle, bold); placed_boxes.append(box_of(t)); return t

fps = {fp.GetReference(): fp for fp in b.GetFootprints()}
def pad_xy(ref, num):
    p = next(p for p in fps[ref].Pads() if p.GetNumber() == num)
    return ToMM(p.GetPosition().x), ToMM(p.GetPosition().y)

j3 = ['GND', 'TX', 'RX', 'EN', 'IO0', '3V3']
for i, s in enumerate(j3):
    x, y = pad_xy('J3', str(i + 1)); label(s, x, y + 2.05, 0.8)
x, y = pad_xy('J3', '1'); label('UART (ESP side)', x - 1.0, y - 2.6, 0.8, LEFT)
j4 = ['VIN', '3V3', 'GND', 'SDA', 'SCL', '18', '19', '23', '25', '26', '32', '33', '34', '35']
for i, s in enumerate(j4):
    x, y = pad_xy('J4', str(i + 1)); label(s, x, y + 2.05, 0.8)
x, y = pad_xy('J4', '1'); label('EXPANSION  (IO34/35 input only)', x - 1.0, y - 2.6, 0.8, LEFT)
x, y = pad_xy('J2', '1'); label('5V IN', x - 0.2, y + 2.0, 0.8); x2, y2 = pad_xy('J2', '2'); label('GND', x2 + 0.6, y2 + 2.0, 0.8)
for ref, s in (('SW1', 'RESET'), ('SW2', 'BOOT'), ('SW3', 'USER IO13')):
    fp = fps[ref]; bb = fp.GetBoundingBox(False, False)
    label(s, ToMM(bb.GetCenter().x), ToMM(bb.GetBottom()) + 0.9, 0.85, bold=True)
label('USB-C', 102.0, 117.0, 0.9, LEFT, bold=True)
label('PWR', 119.2, 121.5, 0.8, RIGHT)
label('IO2', 158.3, 123.0, 0.8, LEFT)
label('IR TX x2', 164.2, 102.4, 0.9, CENTER, bold=True)
label('IR RX', 171.0, 130.6, 0.9, CENTER, bold=True)
label('38 kHz', 171.0, 141.8, 0.8, CENTER)
label('ESP32 IR v2.0', 166.5, 145.4, 1.2, CENTER, bold=True)
label('github.com/abhiramgcos', 166.5, 147.4, 0.8, CENTER)

# ------------------------------------------------------------------ reference designators
bad = 0
for fp in sorted(b.GetFootprints(), key=lambda f: f.GetReference()):
    ref = fp.Reference()
    if fp.GetReference().startswith('H'):
        ref.SetVisible(False); continue
    ref.SetVisible(True)
    ref.SetTextSize(V(0.8, 0.8)); ref.SetTextThickness(mm(0.15))
    ref.SetTextAngle(pcbnew.EDA_ANGLE(0, pcbnew.DEGREES_T)); ref.SetKeepUpright(True)
    fp.Value().SetVisible(False)
    fp.BuildCourtyardCaches()
    cy = fp.GetCourtyard(pcbnew.F_CrtYd)
    bb = cy.BBox() if cy.OutlineCount() else fp.GetBoundingBox(False, False)
    l, t, r, bt = ToMM(bb.GetLeft()), ToMM(bb.GetTop()), ToMM(bb.GetRight()), ToMM(bb.GetBottom())
    cx, cy_ = (l + r) / 2, (t + bt) / 2
    CUR[0] = fp.GetReference()
    if fp.GetReference() == 'U1':
        cands = [(138.0, 116.0)]
    else:
        cands = [(cx, t - 0.55), (cx, bt + 0.55), (l - 1.3, cy_), (r + 1.3, cy_),
                 (l - 1.3, t - 0.5), (r + 1.3, t - 0.5), (l - 1.3, bt + 0.5), (r + 1.3, bt + 0.5),
                 (cx, t - 1.4), (cx, bt + 1.4), (l - 2.2, cy_), (r + 2.2, cy_), (cx, cy_)]
    bad += place_text(ref, cands) > 0

# ------------------------------------------------------------------ back side: title, tables, doodle
text('ESP32 IR BLASTER', 138.0, 104.2, 2.0, B, bold=True)
text('v2.0  |  2026-11  |  abhiramgcos  |  KiCad', 138.0, 106.9, 0.9, B)
# value table (hand-assembly cheat sheet)
vals = collections.OrderedDict()
for c in comps:
    if c['lib'] in ('Device:R', 'Device:C'):
        vals.setdefault(c['value'], []).append(c['ref'])
rows = [f"{v:>6}  {','.join(sorted(r, key=lambda s: (s[0], int(s[1:]))))}" for v, r in vals.items()]
x0, y0 = 148.5, 132.5
text('PASSIVES (0805 unless noted)', x0, y0, 0.9, B, RIGHT, bold=True)
for i, rrow in enumerate(rows):
    text(rrow.replace('22uF', '22uF*').replace('18R', '18R*'), x0, y0 + 0.4 + 1.2 * (i + 1), 0.8, B, RIGHT)
text('* = 1206', x0, y0 + 0.4 + 1.2 * (len(rows) + 1), 0.8, B, RIGHT)
# GPIO map
gx, gy = 104.0, 132.5
gp = ['GPIO MAP', 'IR TX   IO4', 'IR RX   IO16', 'LED     IO2', 'BUTTON  IO13', 'I2C     IO21/22', 'UART0   IO1/3']
for i, s in enumerate(gp):
    text(s, gx, gy + 1.25 * i, 0.9 if i == 0 else 0.8, B, RIGHT, bold=(i == 0))

# doodle: a little robot beaming IR waves at you (original drawing)
cx, cy = 128.0, 141.0
rrect(cx - 4.0, cy - 3.2, cx + 4.0, cy + 3.0, 1.2)            # head
circle((cx - 1.7, cy - 0.6), 0.9); circle((cx + 1.7, cy - 0.6), 0.9)   # eyes
circle((cx - 1.5, cy - 0.5), 0.3, fill=True); circle((cx + 1.9, cy - 0.5), 0.3, fill=True)
arc((cx, cy + 0.9), 1.6, 20, 160)                              # smile
line((cx, cy - 3.2), (cx, cy - 5.0)); circle((cx, cy - 5.5), 0.5)   # antenna
line((cx - 4.0, cy), (cx - 5.0, cy)); line((cx + 4.0, cy), (cx + 5.0, cy))  # ears
rrect(cx - 3.0, cy + 3.6, cx + 3.0, cy + 6.6, 0.8)             # body
circle((cx - 1.2, cy + 5.1), 0.35, fill=True); circle((cx + 1.2, cy + 5.1), 0.35, fill=True)
line((cx + 3.0, cy + 4.6), (cx + 5.6, cy + 4.0))               # arm holding a remote
rrect(cx + 5.4, cy + 2.9, cx + 7.0, cy + 5.2, 0.3)
for k, r in enumerate((1.3, 2.4, 3.5)):                         # IR waves
    arc((cx + 7.4, cy + 3.4), r, -50, 20, w=0.2)
text('beep-boop 38kHz', cx, cy + 8.0, 0.8, B)

pcbnew.ZONE_FILLER(b).Fill(b.Zones())
pcbnew.SaveBoard(PCB, b)
print('silk done; refs needing compromise:', bad)
